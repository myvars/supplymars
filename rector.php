<?php

declare(strict_types=1);

use Rector\Config\RectorConfig;
use Rector\PHPUnit\CodeQuality\Rector\Class_\PreferPHPUnitSelfCallRector;
use Rector\PHPUnit\CodeQuality\Rector\Class_\PreferPHPUnitThisCallRector;
use Rector\PHPUnit\CodeQuality\Rector\Class_\YieldDataProviderRector;
use Rector\PHPUnit\CodeQuality\Rector\ClassMethod\AddInstanceofAssertForNullableArgumentRector;
use Rector\PHPUnit\CodeQuality\Rector\ClassMethod\AddInstanceofAssertForNullableInstanceRector;
use Rector\PHPUnit\CodeQuality\Rector\FuncCall\AssertFuncCallToPHPUnitAssertRector;
use Rector\PHPUnit\CodeQuality\Rector\MethodCall\StringCastAssertStringContainsStringRector;

return RectorConfig::configure()
    ->withPaths([
        __DIR__ . '/src',
        __DIR__ . '/templates',
        __DIR__ . '/tests',
    ])
    ->withRootFiles()
    ->withComposerBased(twig: true, doctrine: true, phpunit: true, symfony: true)
    ->withPhpSets()
    ->withPreparedSets(
        deadCode: true,
        codeQuality: true,
        codingStyle: true,
        typeDeclarations: true,
        privatization: true,
        instanceOf: true,
        earlyReturn: true,
        phpunitCodeQuality: true,
        phpunitMockToStub: true,
        doctrineCodeQuality: true,
    )
    ->withRules([
        // The tests call the static assertions statically: self::assert*()
        PreferPHPUnitSelfCallRector::class,
    ])
    ->withImportNames(importShortClasses: false, removeUnusedImports: true)
    ->withSkip([
        // Regenerated by importmap:require, which writes it without strict_types
        __DIR__ . '/importmap.php',
        // Flips self::assert*() to $this->assert*(); the tests call the static assertions statically
        PreferPHPUnitThisCallRector::class,
        // Add assertInstanceOf() only to narrow a type for PHPStan; tests reload with findOrFail(), and \assert() is enough
        AddInstanceofAssertForNullableInstanceRector::class,
        AddInstanceofAssertForNullableArgumentRector::class,
        AssertFuncCallToPHPUnitAssertRector::class,
        // Casts a nullable message with (string), which hides a null rather than failing on it
        StringCastAssertStringContainsStringRector::class,
        // Rewrites providers as \Iterator and moves trailing comments onto the wrong row; providers here yield labelled rows
        YieldDataProviderRector::class,
    ]);
